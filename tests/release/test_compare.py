def test_clip_keyed_documents_compare_the_sample_clips_only(tmp_path):
    a = {"summary": {"n": 184}, "clips": {"c1": {"z": 1.0}, "c2": {"z": 2.0}}}
    b = {"summary": {"n": 2}, "clips": {"c1": {"z": 1.0}}}
    pa, pb = _pair(tmp_path, "data/h2o/INTAKE/support_audit.json", a, b)
    rel = "data/h2o/INTAKE/support_audit.json"
    assert _file_diff(rel, pa, pb, RULES, frozenset({"c1"})) == ""
    assert _file_diff(rel, pa, pb, RULES, frozenset({"c1", "c2"}))  # a sample clip missing on one side
    assert _file_diff(rel, pa, pb, RULES)  # whole document without a sample


def test_digest_reference_round_trip(tmp_path):
    _pair(tmp_path, "k/x.npz", {"q": np.ones(2)}, {"q": np.ones(2)})
    _pair(tmp_path, "k/y.json", {"v": 1}, {"v": 1})
    rels = ["k/x.npz", "k/y.json"]
    ref = tmp_path / "ref.tsv"
    assert C.write_ref(ref, C.root_units(tmp_path / "b", rels, RULES)) == 2
    assert not C.compare_units(C.root_units(tmp_path / "a", rels, RULES), C.read_ref(ref), rels)["differ"]
    np.savez(tmp_path / "a" / "k" / "x.npz", q=np.zeros(2))
    res = C.compare_units(C.root_units(tmp_path / "a", rels, RULES), C.read_ref(ref), rels)
    assert not res["differ"] and res["numeric"] == {"k/x.npz": {"q": None}}  # a value change is numeric: reported
    np.savez(tmp_path / "a" / "k" / "x.npz", q=np.zeros(3))
    assert C.compare_units(C.root_units(tmp_path / "a", rels, RULES), C.read_ref(ref), rels)["differ"]  # shape


def test_digest_is_canonical():
    assert C.digest_value({"b": 1, "a": [1.0, None]}) == C.digest_value({"a": [1.0, None], "b": 1})
    assert C.digest_value(float("nan")) == C.digest_value(float("nan"))
    assert C.digest_value(1) != C.digest_value(1.0) != C.digest_value(True)
    assert C.digest_value((1,)) != C.digest_value([1])
    with pytest.raises(TypeError):
        C.digest_value(object())


def test_torch_tensors_digest_by_value():
    torch = pytest.importorskip("torch")
    t = torch.arange(3, dtype=torch.float32)
    assert C.digest_value({"x": t}) == C.digest_value({"x": t.clone()})
    assert C.digest_value(t) != C.digest_value(t.numpy())  # a tensor is not an array
    assert C.digest_value(t) != C.digest_value(t.double())


def _usda(path, doc):
    path.write_text('#usda 1.0\n(\n    doc = "' + doc + '"\n)\n\ndef Xform "r"\n{\n}\n')


def test_usd_needs_pxr_and_usd_meta_clears_only_documentation(tmp_path, monkeypatch):
    f = tmp_path / "x.usda"
    _usda(f, "/abs/path")
    monkeypatch.setitem(__import__("sys").modules, "pxr", None)
    with pytest.raises(SystemExit, match="needs pxr"):
        C.units("a/x.usda", f, [])
    bad = tmp_path / "r.tsv"
    bad.write_text("rule\tfiles\tmatch\twhy\nusd_meta\t*.usd\tcustomLayerData\tno\n")
    with pytest.raises(SystemExit, match="usd_meta clears"):
        C.load_rules(bad)


def test_usd_documentation_rule(tmp_path):
    pytest.importorskip("pxr")
    a, b = tmp_path / "a.usda", tmp_path / "b.usda"
    _usda(a, "/one/place")
    _usda(b, "/other/place")
    rule = [C.Rule("usd_meta", "*.usda", "documentation", "bake place")]
    assert C.diff_units(C.units("a.usda", a, rule), C.units("a.usda", b, rule)) == ("", [])
    assert C.diff_units(C.units("a.usda", a, []), C.units("a.usda", b, []))[0]


def test_ref_mode_checks_files_of_both_lists(tmp_path):
    # A file the reference lists but the run's --paths leaves out (or the run did not make) fails as only_b; a file
    # the run made that the reference lacks fails as only_a.
    _pair(tmp_path, "k/x.npz", {"q": np.ones(2)}, {"q": np.ones(2)})
    _pair(tmp_path, "k/y.json", {"v": 1}, {"v": 1})
    ref = tmp_path / "ref.tsv"
    C.write_ref(ref, C.root_units(tmp_path / "b", ["k/x.npz", "k/y.json"], RULES))
    paths = tmp_path / "paths.txt"
    paths.write_text("k/x.npz\n")
    (tmp_path / "a" / "k" / "y.json").unlink()
    assert C.main(["--a", str(tmp_path / "a"), "--ref", str(ref), "--paths", str(paths)]) == 1
    (tmp_path / "a" / "k" / "y.json").write_text(json.dumps({"v": 1}))
    assert C.main(["--a", str(tmp_path / "a"), "--ref", str(ref), "--paths", str(paths)]) == 0
    (tmp_path / "a" / "k" / "z.json").write_text("{}")
    paths.write_text("k/x.npz\nk/z.json\n")
    assert C.main(["--a", str(tmp_path / "a"), "--ref", str(ref), "--paths", str(paths)]) == 1


def test_pass_rule_is_the_verdicts(tmp_path):
    """Same verdicts → pass (float values and stamps may differ, reported); another verdict → fail."""
    a = {
        "verdict": "adopted",
        "reason": "ok",
        "n": 3,
        "q": [0.1, 0.2],
        "time": "2026-11-22T15:29:38+0900",
        "provenance": {"retarget_input": {"stat": "25c74c7e"}},
        "src": "/var/tmp/root/x",
        "rules": {"W": {"fp": "ab"}},
    }
    b = {
        "verdict": "adopted",
        "reason": "ok",
        "n": 3,
        "q": [0.1000001, 0.2],
        "time": "2026-11-22T15:50:54+0900",
        "provenance": {"retarget_input": {"stat": "06cc666b"}},
        "src": "/tmp/other/x",
        "rules": {"W": {"fp": "cd"}},
    }
    rel = "data/taco/base/h/bimanual/c/t.json"
    assert _cmp(tmp_path / "s", rel, a, b) == "numeric: ['-']"
    assert _cmp(tmp_path / "r", rel, a, dict(b, verdict="rejected")).startswith("units differ")
    assert _cmp(tmp_path / "w", rel, a, dict(b, reason="no_contact")).startswith("units differ")
    assert _cmp(tmp_path / "k", rel, a, dict(b, n=4)).startswith("units differ")
    x = {"ang_vel": np.ones((4, 3), np.float32), "flags": np.array([0, 1, 0, 0])}
    y = {"ang_vel": np.ones((4, 3), np.float32) + np.float32(1e-6), "flags": np.array([0, 1, 0, 0])}
    pa, pb = _pair(tmp_path / "n", "d/b.npz", x, y)
    res = C.compare_roots(pa.parents[1], pb.parents[1], ["d/b.npz"], RULES)
    assert not res["differ"] and res["numeric"]["d/b.npz"]["ang_vel"] == pytest.approx(1e-6, rel=0.2)
    pa, pb = _pair(tmp_path / "f", "d/b.npz", x, dict(y, flags=np.array([0, 1, 1, 0])))
    assert C.compare_roots(pa.parents[1], pb.parents[1], ["d/b.npz"], RULES)["differ"]
