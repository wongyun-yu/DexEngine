"""The release comparison: equal content passes, any other difference fails, and only the rows of the rules file
are skipped (negative tests: each rule kind ignores its value and nothing else)."""

from __future__ import annotations

import json
import pickle
from pathlib import Path

import numpy as np
import pytest

from dexengine.release import compare as C

RULES = [
    C.Rule("json_key", "data/*/INTAKE/hand_dir.json", "time", "clock"),
    C.Rule("json_key", "x/*/prov.json", "tree.commit", "commit"),
    C.Rule("line", "x/*.urdf", "^<!-- GENERATED by ", "comment"),
    C.Rule("file", "x/skip.bin", "-", "not compared"),
]


def _pair(tmp_path: Path, rel: str, a, b) -> tuple[Path, Path]:
    pa, pb = tmp_path / "a" / rel, tmp_path / "b" / rel
    for p, v in ((pa, a), (pb, b)):
        p.parent.mkdir(parents=True, exist_ok=True)
        if rel.endswith(".npz"):
            np.savez(p, **v)
        elif rel.endswith(".pkl"):
            p.write_bytes(pickle.dumps(v))
        elif rel.endswith(".json"):
            p.write_text(json.dumps(v))
        else:
            p.write_bytes(v)
    return pa, pb


def _file_diff(rel, a, b, rules, clips=None) -> str:
    """'' when equal, the verdict finding, or `numeric: [units]` (reported, not failed)."""
    why, num = C.diff_units(C.units(rel, a, rules, clips), C.units(rel, b, rules, clips))
    return why or (f"numeric: {num}" if num else "")


def _cmp(tmp_path, rel, a, b) -> str:
    pa, pb = _pair(tmp_path, rel, a, b)
    return _file_diff(rel, pa, pb, RULES)


def test_arrays_by_name_dtype_shape_bytes(tmp_path):
    x = {"q": np.arange(6, dtype=np.float32).reshape(2, 3)}
    assert _cmp(tmp_path, "d/a.npz", x, {"q": x["q"].copy()}) == ""
    assert _cmp(tmp_path, "d/b.npz", x, {"q": x["q"].astype(np.float64)})
    assert _cmp(tmp_path, "d/c.npz", x, {"q": x["q"].reshape(3, 2)})
    y = x["q"].copy()
    y[0, 0] = np.nextafter(y[0, 0], 1, dtype=np.float32)
    assert _cmp(tmp_path, "d/d.npz", x, {"q": y})
    assert _cmp(tmp_path, "d/e.npz", x, {**x, "extra": np.zeros(1)})


def test_pickle_by_content(tmp_path):
    v = {"a": np.ones(3), "b": [1, 2.5, "s"]}
    assert _cmp(tmp_path, "p/a.pkl", v, {"b": [1, 2.5, "s"], "a": np.ones(3)}) == ""
    assert _cmp(tmp_path, "p/b.pkl", v, {"a": np.ones(3), "b": [1, 2.5000001, "s"]})


def test_json_key_rule_drops_only_its_path_and_file(tmp_path):
    a = {"time": "t1", "v": 1}
    assert _cmp(tmp_path, "data/taco/INTAKE/hand_dir.json", a, {"time": "t2", "v": 1}) == ""
    assert _cmp(tmp_path, "data/taco/INTAKE/hand_dir.json", a, {"time": "t2", "v": 2})
    assert _cmp(tmp_path, "data/taco/INTAKE/other.json", a, {"time": "t2", "v": 1})  # rule is per file
    p = {"tree": {"commit": "c1"}, "hands": [{"commit": "h"}]}
    assert _cmp(tmp_path, "x/r_truncated/prov.json", p, {"tree": {"commit": "c2"}, "hands": [{"commit": "h"}]}) == ""
    assert _cmp(tmp_path, "x/r_truncated/prov.json", p, {"tree": {"commit": "c1"}, "hands": [{"commit": "z"}]})


def test_line_and_file_rules(tmp_path):
    a = b"<!-- GENERATED by old.py -->\n<robot/>\n"
    assert _cmp(tmp_path, "x/r.urdf", a, b"<!-- GENERATED by new.py -->\n<robot/>\n") == ""
    assert _cmp(tmp_path, "x/r.urdf", a, b"<!-- GENERATED by new.py -->\n<robot name='x'/>\n")
    assert _cmp(tmp_path, "y/r.urdf", a, b"<!-- GENERATED by new.py -->\n<robot/>\n")
    assert _cmp(tmp_path, "x/skip.bin", b"1", b"2") == ""
    assert _cmp(tmp_path, "x/other.bin", b"1", b"2")


def test_roots_report_one_sided_files(tmp_path):
    _pair(tmp_path, "k/same.bin", b"1", b"1")
    (tmp_path / "a" / "k" / "only.bin").write_bytes(b"1")
    res = C.compare_roots(tmp_path / "a", tmp_path / "b", ["k/same.bin", "k/only.bin", "k/none.bin"], RULES)
    assert res["equal"] == ["k/same.bin"] and res["only_a"] == ["k/only.bin"] and "k/none.bin" in res["differ"]


