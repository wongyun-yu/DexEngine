"""Coordinate frames, object slots and the scene-setup (support) rules — the one owner module.

Every name is defined in a submodule of this package and re-exported here; callers use
`from dexengine.placement.coords import core as C` and `C.<name>`.

Two traps this module exists for:
  ■ Two coordinate frames. The qpos in `trajectory_kinematic.npz` is in **capture coordinates**; scene (env-local)
    coordinates are Rz(−90°)·capture + [0, 0, DESK_HEIGHT] (scene_x = capture_y, scene_y = −capture_x). The robot
    base and the desk bounds are in scene coordinates — comparing a capture-frame object directly against them is off
    by about 0.5 m.
  ■ Object slots differ per dataset. Objects are blocks of 7 qpos columns (xyz + wxyz) whose place depends on the
    tree's layout (raw TACO D=50 → columns 36–42 and 43–49; baked robot D=70 → columns 56–62 and 63–69, where
    columns 36–37 are robot joints). Read them with `tree_object_slots(tree_dir)`.

Submodules:
  thresholds    rule thresholds and stamp vocabulary (literal constants — the rules registry reads them by source)
  frames        frames · scene mode · desk boxes · object slots · placement formula · robot standing spot
  objects       object meshes · placed vertices · base↔tree frame maps · tree records
  contacts      contact sidecars · "holds" · "touches" · start state of the main objects
  discs         disc stamp vocabulary · rest-interval discs
  support_kind  support objects and the start support kind of every main object
  pedestals     fixed-object · moved-extra rest · end pedestals (desk scenes)
  stamp         compute · stamp · read the support statement · tree → world z offset
  setup         code/data inputs of the setup computation · staleness of a stamp
"""

