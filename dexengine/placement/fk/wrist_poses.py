#!/usr/bin/env python3
"""Pre-compute wrist poses from body_positions.npz for arm IK precompute.

This script derives wrist poses from body FK.
It reads per-sequence body_positions.npz files (generated by
dexengine/placement/fk/body_positions.py), extracts palm pose, and saves per-clip
wrist pose files compatible with TrajectoryManager._load_wrist_poses.

Input (per sequence):
    {data_dir}/{sequence}/0/body_positions.npz

Required keys:
    - right_hand_body_pos / left_hand_body_pos : (T, B, 3)
    - right_hand_body_quat / left_hand_body_quat : (T, B, 4) wxyz
    - right_hand_body_names / left_hand_body_names : (B,)

Output schema:
    positions:   (T, 3) float32
    quaternions: (T, 4) float32 wxyz

Coordinate convention:
    body_positions.npz stores MuJoCo FK world poses in replay convention
    (+Y forward, no desk-height offset). Therefore this script applies NO extra
    rotation/translation. Rz(-90deg) and traj_offset_z are still applied later
    by TrajectoryManager._load_wrist_poses at runtime.

Usage (--data_dir and --output_dir are both required; the paths come from the layer owner, e.g. data.stages step 6 /
chain_fast.sh):
    python -m dexengine.placement.fk.wrist_poses \
        --data_dir <base or tree dir> \
        --output_dir precompute/<ds>/robots/<hand spec dir>/wrist_poses_right --side right

    # Single sequence
    python -m dexengine.placement.fk.wrist_poses \
        --data_dir <tree root> --output_dir <combo root>/wrist_poses_left --side left \
        --sequence <tree name>
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import numpy as np

from dexengine.core.errors import InputMissingError
from dexengine.core.paths import stage_banner

_BODY_SUBDIR_CANDIDATES = ["0", ""]


#: Stale reasons — the keys of the `[WRIST_CACHE] … stale_reasons=` marker. A cache is fresh only when its arrays equal
#: the ones extracted from the current body_positions; what changed body_positions is not asked (the content is the
#: answer). mtime is not used: rewrites that keep the content would make every cache look stale.
STALE_REASONS = ("absent", "unreadable", "differs")


def stale_reason(out_path, positions: np.ndarray, quaternions: np.ndarray) -> str | None:
    """Whether one cache file holds the same values as the wrist just extracted: None = fresh, else a STALE_REASONS key.

    The stored arrays (float32) and the extracted ones are compared with `array_equal`, dtype included — no
    renormalisation. Equal values are not rewritten, so the bytes (and the f0 key that hashes them) stay the same.
    The keys are actually decompressed, so a truncated npz is caught as `unreadable`.
    """
    if not os.path.isfile(out_path):
        return "absent"
    try:
        with np.load(out_path) as d:
            sp, sq = d["positions"], d["quaternions"]  # real decompression — a truncated zip raises here
    except Exception:  # noqa: BLE001 — anything unreadable is rebuilt (a false positive only costs time)
        return "unreadable"
    same = (
        sp.dtype == positions.dtype
        and sq.dtype == quaternions.dtype
        and np.array_equal(sp, positions)
        and np.array_equal(sq, quaternions)
    )
    return None if same else "differs"


def cache_state(body_npz_path: str, out_path, side: str) -> tuple[str | None, np.ndarray, np.ndarray]:
    """(stale reason or None, extracted positions, extracted quaternions). The extraction runs once, and the comparison
    and the write use the same arrays. Every freshness check of this cache (main, freshness, the f0 prejudge upstream
    check) calls this function."""
    positions, quaternions = extract_wrist_poses_from_body_positions(body_npz_path, side=side)
    return stale_reason(out_path, positions, quaternions), positions, quaternions


def tree_fresh(ds: str, spec_dir: str, tree) -> bool:
    """Whether every side cache of one tree equals what its current body_positions gives (read-only, creates nothing).

    The sides are the embodiment's sides (data.stage1.table.emb_sides) and the cache location is paths.wrist_base_dir. A
    tree without body_positions, or whose wrist cannot be extracted, is not fresh."""
    from dexengine.core import paths as P  # noqa: PLC0415
    from dexengine.data.stage1.table import emb_sides  # noqa: PLC0415 — owner of the emb -> sides rule

    tree = Path(tree)
    emb = next(
        (e for e in P.data_layout.EMBODIMENTS if P.layer_path("base", ds, hand=spec_dir, emb=e) == tree.parent), None
    )
    bp = find_body_positions_file(str(tree))
    if emb is None or bp is None:
        return False
    try:
        return all(
            cache_state(bp, P.wrist_base_dir(spec_dir, side, ds) / f"{tree.name}.npz", side)[0] is None
            for side in emb_sides(emb)
        )
    except (Exception, SystemExit):  # noqa: BLE001 — a tree that cannot be extracted (no palm, ...) is not fresh
        return False


def freshness(ds: str, spec_dir: str) -> tuple[int, int]:
    """(base trees whose side caches are all fresh, all base trees) — the wrist-cache column of the data stages
    (per tree: tree_fresh; the tree list: support.gap._base_trees)."""
    from dexengine.data.support import gap as SG  # noqa: PLC0415 — the base-tree list of the stage-1 columns

    trees = SG._base_trees(ds, spec_dir)
    return sum(tree_fresh(ds, spec_dir, d) for d in trees), len(trees)


def find_body_positions_file(seq_dir: str) -> str | None:
    """Locate body_positions.npz inside a sequence directory."""
    for subdir in _BODY_SUBDIR_CANDIDATES:
        path = os.path.join(seq_dir, subdir, "body_positions.npz")
        if os.path.isfile(path):
            return path
    return None


def list_sequence_dirs(data_dir: str, sequence_filter: str | None) -> list[str]:
    """Return tree names: folders holding body_positions.npz and, for a whole-layer run (no --sequence filter), also
    base trees (task_info.json) without one, so the loop records them as FAILED instead of ending rc 0 with an uncached
    tree. A filtered run (one tree in the combo trees layer, where a sibling may be mid-bake) lists only folders with
    body_positions.npz."""
    if not os.path.isdir(data_dir):
        raise FileNotFoundError(f"data_dir does not exist: {data_dir}")

    seq_names: list[str] = []
    for entry in sorted(os.listdir(data_dir)):
        full = os.path.join(data_dir, entry)
        if not os.path.isdir(full):
            continue
        if sequence_filter is not None and sequence_filter not in entry:
            continue
        if find_body_positions_file(full) is not None or (
            sequence_filter is None and os.path.isfile(os.path.join(full, "task_info.json"))
        ):
            seq_names.append(entry)
    return seq_names


def _to_name_list(arr: np.ndarray) -> list[str]:
    """Convert np array of names into a Python list[str]."""
    names = arr.tolist()
    if isinstance(names, str):
        return [names]
    return [str(x) for x in names]


def _canonicalize_quat_wxyz(quat: np.ndarray) -> np.ndarray:
    """Normalize and canonicalize quaternion sequence in wxyz format."""
    q = quat.astype(np.float64, copy=True)

    norms = np.linalg.norm(q, axis=-1, keepdims=True)
    norms = np.maximum(norms, 1e-12)
    q /= norms

    # Canonical sign: w >= 0
    flip = q[:, 0] < 0
    q[flip] = -q[flip]

    # Temporal continuity: avoid +-q flips frame-to-frame
    for t in range(1, q.shape[0]):
        if np.dot(q[t], q[t - 1]) < 0:
            q[t] = -q[t]

    return q.astype(np.float32)


def _registry_palm_names(side: str) -> dict[str, str]:
    """FK palm body names of every hand spec in the registry, mirrored to ``side`` — {palm name: hand id}."""
    from dexengine.core import hands as _HS  # noqa: PLC0415

    out: dict[str, str] = {}
    for hid, sp in _HS.HAND_REGISTRY.items():
        n = getattr(sp, "palm_fk_body_right", "") if sp is not None else ""
        if n:
            out.setdefault(n.replace("right_", f"{side}_", 1), hid)
    return out


def _resolve_palm_index(body_names: list[str], side: str) -> int:
    """Index of the palm body in the FK body list.

    Candidates = HandSpec.palm_fk_body_right of every registered hand, mirrored to ``side``; exactly one must match,
    otherwise this raises (no index-0 fallback). When DEXENGINE_HAND is set, the matched palm must belong to that hand
    (guards against reading another hand's rig).
    """
    cand = _registry_palm_names(side)
    hits = [n for n in cand if n in body_names]
    if len(hits) != 1:
        raise InputMissingError(
            f"[wrist_poses_from_body_positions] cannot pick the palm body (side={side}, candidate matches {hits}) — "
            f"body_names={body_names[:8]}… check this hand's HandSpec.palm_fk_body_right"
        )
    _h = os.environ.get("DEXENGINE_HAND", "").strip()
    if _h and cand[hits[0]] != _h and _h in cand.values():
        raise SystemExit(
            f"[wrist_poses_from_body_positions] palm {hits[0]!r} belongs to hand {cand[hits[0]]} "
            f"but DEXENGINE_HAND={_h} — "
            f"reading another hand's retargeting output"
        )
    return body_names.index(hits[0])


def extract_wrist_poses_from_body_positions(
    body_npz_path: str,
    side: str,
) -> tuple[np.ndarray, np.ndarray]:
    """Extract wrist positions/quaternions from body_positions.npz.

    Returns:
        positions: (T, 3) float32
        quaternions: (T, 4) float32 wxyz
    """
    data = np.load(body_npz_path, allow_pickle=True)

    body_pos_key = f"{side}_hand_body_pos"
    body_quat_key = f"{side}_hand_body_quat"
    body_names_key = f"{side}_hand_body_names"

    missing = [k for k in (body_pos_key, body_quat_key, body_names_key) if k not in data.files]
    if missing:
        raise KeyError(f"{body_npz_path} missing required keys: {missing}. Available keys: {list(data.files)}")

    body_pos = data[body_pos_key]  # (T, B, 3)
    body_quat = data[body_quat_key]  # (T, B, 4) wxyz
    body_names = _to_name_list(data[body_names_key])

    if body_pos.ndim != 3 or body_pos.shape[-1] != 3:
        raise ValueError(f"{body_npz_path} {body_pos_key} has bad shape: {body_pos.shape}")
    if body_quat.ndim != 3 or body_quat.shape[-1] != 4:
        raise ValueError(f"{body_npz_path} {body_quat_key} has bad shape: {body_quat.shape}")
    if body_pos.shape[0] != body_quat.shape[0] or body_pos.shape[1] != body_quat.shape[1]:
        raise ValueError(f"{body_npz_path} position/quaternion shape mismatch: {body_pos.shape} vs {body_quat.shape}")

    palm_idx = _resolve_palm_index(body_names, side)

    positions = body_pos[:, palm_idx, :].astype(np.float32, copy=True)
    quaternions = _canonicalize_quat_wxyz(body_quat[:, palm_idx, :])
    return positions, quaternions


def _report(args, output_dir: str, processed: int, fresh: int, reasons: dict, failed: list, total_frames: int) -> int:
    """End of a side run: summary, the [WRIST_CACHE] marker, rc (1 if anything failed)."""
    print(f"\n{'=' * 70}")
    print("Pre-computation complete")
    print(f"  Processed: {processed}")
    print(f"  Skipped (fresh): {fresh}")
    print(f"  Failed:    {len(failed)}")
    print(f"  Total frames: {total_frames}")
    print(f"  Output dir: {output_dir}")
    if failed:
        print("\nFailures:")
        for seq, err in failed[:10]:
            print(f"  - {seq}: {err}")
        if len(failed) > 10:
            print(f"  ... and {len(failed) - 10} more")
    print(f"{'=' * 70}")
    # Marker that this side run compared the caches by content (the data stages count these lines).
    # rebuilt = caches written (counted per stale reason; without --skip_fresh equal values are rewritten too and not
    # counted under a reason).
    print(
        f"[WRIST_CACHE] side={args.side} skip_fresh={int(args.skip_fresh)} fresh={fresh} rebuilt={processed} "
        f"failed={len(failed)} stale_reasons="
        + ",".join(f"{k}:{v}" for k, v in reasons.items())
        + f" out={output_dir}",
        flush=True,
    )
    return 0 if not failed else 1


def _parse_args():
    """Command line of the wrist-pose pre-compute."""
    parser = argparse.ArgumentParser(description="Pre-compute wrist poses from body_positions.npz (MuJoCo FK).")
    parser.add_argument("--data_dir", type=str, required=True, help="Path to processed trajectory dataset directory.")
    parser.add_argument(
        "--output_dir",
        type=str,
        required=True,
        help="Output directory for per-clip .npz files (required — no default).",
    )
    parser.add_argument("--sequence", type=str, default=None, help="Optional substring filter on sequence name.")
    parser.add_argument(
        "--side", type=str, default="right", choices=["right", "left"], help="Which hand palm to export. Default: right"
    )
    parser.add_argument(
        "--skip_fresh",
        action="store_true",
        help="do not rewrite a cache that equals what the current body_positions gives "
        "(a different, missing or unreadable cache is rewritten)",
    )
    args = parser.parse_args()
    return args


def _print_header(data_dir, output_dir, args, seq_names):
    """The run header (inputs, side, count, transform, freshness rule)."""
    print(f"\n{'=' * 70}")
    print("Pre-computing wrist poses from body_positions.npz")
    print(f"  data_dir:       {data_dir}")
    print(f"  output_dir:     {output_dir}")
    print(f"  side:           {args.side}")
    print(f"  sequences:      {len(seq_names)}" + (f" (filter: '{args.sequence}')" if args.sequence else ""))
    print("  transform:      none (already replay convention; runtime applies Rz(-90)+z)")
    print(f"  skip_fresh:     {args.skip_fresh}")
    print(f"{'=' * 70}\n")


def main() -> None:
    args = _parse_args()

    data_dir = os.path.abspath(args.data_dir)
    output_dir = os.path.abspath(args.output_dir)
    os.makedirs(output_dir, exist_ok=True)

    seq_names = list_sequence_dirs(data_dir, args.sequence)
    stage_banner(
        f"wrist_poses[{args.side}]",
        reads=[data_dir],
        writes=[output_dir],
        inputs=seq_names,
        probe=lambda s: os.path.isfile(os.path.join(data_dir, s, "0", "body_positions.npz")),
    )
    if not seq_names:
        print(
            f"[precompute_wrist_poses_from_body_positions] "
            f"No sequences found under {data_dir}" + (f" matching '{args.sequence}'" if args.sequence else ""),
            file=sys.stderr,
        )
        sys.exit(1)

    _print_header(data_dir, output_dir, args, seq_names)

    processed = 0
    fresh = 0
    reasons = dict.fromkeys(STALE_REASONS, 0)
    failed: list[tuple[str, str]] = []
    total_frames = 0

    for i, seq_name in enumerate(seq_names):
        out_path = os.path.join(output_dir, f"{seq_name}.npz")
        seq_dir = os.path.join(data_dir, seq_name)
        body_npz_path = find_body_positions_file(seq_dir)
        if body_npz_path is None:
            failed.append((seq_name, "body_positions.npz not found"))
            print(f"  [{i + 1}/{len(seq_names)}] {seq_name}: FAILED (missing body_positions.npz)")
            continue

        try:
            # one extraction — the freshness check and the write use the same arrays (cache_state)
            why, positions, quaternions = cache_state(body_npz_path, out_path, args.side)
            if args.skip_fresh and why is None:
                fresh += 1
                continue
            np.savez(out_path, positions=positions, quaternions=quaternions)
        except Exception as e:  # noqa: BLE001 — one sequence's failure is recorded; the batch goes on
            failed.append((seq_name, str(e)))
            print(f"  [{i + 1}/{len(seq_names)}] {seq_name}: FAILED ({e})")
            continue
        if why is not None:
            reasons[why] += 1

        total_frames += positions.shape[0]
        processed += 1
        if processed <= 5 or processed % 50 == 0 or (i + 1) == len(seq_names):
            print(
                f"  [{i + 1}/{len(seq_names)}] {seq_name}: "
                f"T={positions.shape[0]}, "
                f"pos[0]={positions[0].tolist()}, "
                f"quat[0]={quaternions[0].tolist()}"
            )

    sys.exit(_report(args, output_dir, processed, fresh, reasons, failed, total_frames))


if __name__ == "__main__":
    from dexengine.core import blas_pin  # stage-1 entry: pinned OpenBLAS kernel, proven

    blas_pin.apply("dexengine.placement.fk.wrist_poses")
    main()
